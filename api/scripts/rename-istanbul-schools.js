// One-off rename: strip redundant "Özel" / il / ilçe words from İstanbul ortaokul
// names inserted by seed-istanbul-schools.js. Province and district are already
// stored as separate columns, so repeating them (or the private-school tag)
// inside the name is pure noise. Keeps "İstanbul" where it's part of a specific
// named institution (İstanbul Üniversitesi, İstanbul Erkek Lisesi, TED İstanbul
// Koleji) or is the only distinguishing word left. If the cleaned name already
// belongs to another row in the same district (e.g. a campus seeded earlier by
// seed-bilfen-schools.js under a shorter name), the duplicate row is deleted
// instead of renamed.
// Usage: node api/scripts/rename-istanbul-schools.js
const fs = require('fs')
const path = require('path')
const sql = require('mssql')

const localSettingsPath = path.join(__dirname, '..', 'local.settings.json')

function loadLocalSettings() {
  if (!fs.existsSync(localSettingsPath)) return
  const parsed = JSON.parse(fs.readFileSync(localSettingsPath, 'utf8'))
  Object.entries(parsed.Values || {}).forEach(([key, value]) => {
    if (!process.env[key] && typeof value === 'string') process.env[key] = value
  })
}

