async function main() {
  loadLocalSettings()
  const connectionString = process.env.SQL_CONNECTION_STRING
  if (!connectionString) throw new Error('SQL_CONNECTION_STRING is missing.')

  const pool = await sql.connect(connectionString)
  try {
    const provinceResult = await pool
      .request()
      .input('name', sql.NVarChar(50), 'İstanbul')
      .query('SELECT TOP 1 id FROM dbo.Provinces WHERE name = @name;')
    const provinceId = provinceResult.recordset[0]?.id
    if (!provinceId) throw new Error('İstanbul province not found.')

    const districtCache = new Map()
    let renamed = 0
    let deletedDuplicates = 0
    let notFound = 0

    for (const [oldName, newName, districtName] of RENAMES) {
      let districtId = districtCache.get(districtName)
      if (districtId === undefined) {
        const districtResult = await pool
          .request()
          .input('provinceId', sql.UniqueIdentifier, provinceId)
          .input('districtName', sql.NVarChar(50), districtName)
          .query('SELECT TOP 1 id FROM dbo.Districts WHERE province_id = @provinceId AND name = @districtName;')
        districtId = districtResult.recordset[0]?.id || null
        districtCache.set(districtName, districtId)
      }
      if (!districtId) {
        console.error(`SKIP: district not found for ${oldName} (${districtName})`)
        notFound++
        continue
      }

      try {
        const updateResult = await pool
          .request()
          .input('districtId', sql.UniqueIdentifier, districtId)
          .input('oldName', sql.NVarChar(200), oldName)
          .input('newName', sql.NVarChar(200), newName)
          .query(`
            UPDATE dbo.Schools SET name = @newName
            WHERE district_id = @districtId AND name = @oldName;
          `)

        if (updateResult.rowsAffected[0] > 0) {
          console.log(`Renamed: "${oldName}" -> "${newName}" (${districtName}/İstanbul)`)
          renamed++
        } else {
          console.error(`NOT FOUND IN DB: "${oldName}" (${districtName}/İstanbul)`)
          notFound++
        }
      } catch (error) {
        if (!/unique index|duplicate key/i.test(error.message)) throw error

        // A row with the cleaned name already exists in this district (e.g.
        // seeded earlier by another script) — same school, so drop our copy.
        const deleteResult = await pool
          .request()
          .input('districtId', sql.UniqueIdentifier, districtId)
          .input('oldName', sql.NVarChar(200), oldName)
          .query(`DELETE FROM dbo.Schools WHERE district_id = @districtId AND name = @oldName;`)

        console.log(`Duplicate of existing row, deleted: "${oldName}" (${districtName}/İstanbul)`)
        deletedDuplicates += deleteResult.rowsAffected[0]
      }
    }

    console.log(`\nDone. Renamed: ${renamed}, deleted duplicates: ${deletedDuplicates}, not found: ${notFound}.`)
  } finally {
    await pool.close()
  }
}

main().catch((error) => {
  console.error(error.message)
  process.exit(1)
})
